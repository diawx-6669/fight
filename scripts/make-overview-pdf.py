# --- страница ---------------------------------------------------------------

PAGE_W, PAGE_H = A4
MARGIN = 26 * mm


def decorate(canvas, doc):
    """Колонтитул. На обложке не рисуется."""
    canvas.saveState()
    if doc.page > 1:
        canvas.setFont("Body", 8)
        canvas.setFillColor(ASH)
        canvas.drawString(MARGIN, 14 * mm, "SHADOWSTRIKE")
        canvas.drawRightString(PAGE_W - MARGIN, 14 * mm, str(doc.page - 1))
        canvas.setStrokeColor(RULE)
        canvas.setLineWidth(0.4)
        canvas.line(MARGIN, 18 * mm, PAGE_W - MARGIN, 18 * mm)
    canvas.restoreState()


def cover_decorate(canvas, doc):
    """Обложка: широкая полоса цвета и метка сверху."""
    canvas.saveState()
    canvas.setFillColor(INK)
    canvas.rect(0, PAGE_H - 12 * mm, PAGE_W, 12 * mm, stroke=0, fill=1)
    canvas.setFillColor(EMBER)
    canvas.rect(0, PAGE_H - 12 * mm, PAGE_W * 0.34, 12 * mm, stroke=0, fill=1)

    canvas.setFillColor(EMBER)
    canvas.rect(MARGIN, 30 * mm, 46 * mm, 3.2 * mm, stroke=0, fill=1)
    canvas.restoreState()


