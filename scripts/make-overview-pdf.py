def h1(text):
    return KeepTogether([
        Paragraph(text, S["h1"]),
        HRFlowable(width="100%", thickness=2, color=EMBER,
                   spaceBefore=3, spaceAfter=9, hAlign="LEFT"),
    ])


def h2(text):
    return Paragraph(text, S["h2"])


def p(text):
    return Paragraph(text, S["p"])


def bullets(items):
    return ListFlowable(
        [ListItem(Paragraph(t, S["li"]), leftIndent=14, value="circle") for t in items],
        bulletType="bullet", start="circle", bulletColor=EMBER,
        bulletFontSize=5, leftIndent=14, spaceAfter=8,
    )


def callout(text):
    """Врезка на плашке — для мыслей, которые стоит прочитать отдельно."""
    inner = Paragraph(text, S["quote"])
    t = Table([[inner]], colWidths=[158 * mm])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), PANEL),
        ("LINEBEFORE", (0, 0), (0, -1), 2.5, EMBER),
        ("LEFTPADDING", (0, 0), (-1, -1), 11),
        ("RIGHTPADDING", (0, 0), (-1, -1), 11),
        ("TOPPADDING", (0, 0), (-1, -1), 9),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    # Врезка не умеет отступом снизу сама — соседний абзац иначе прилипает.
    return KeepTogether([t, Spacer(1, 12)])


