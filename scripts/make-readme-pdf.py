# --- строительные блоки ------------------------------------------------------

class Heading(Paragraph):
    """Заголовок раздела, который попадает в оглавление."""


def h1(text):
    para = Heading(text, S["h1"])
    return [
        CondPageBreak(85 * mm),
        para,
        HRFlowable(width="100%", thickness=2, color=EMBER,
                   spaceBefore=3, spaceAfter=9, hAlign="LEFT"),
    ]


def h2(text):
    # Подзаголовок не остаётся один внизу страницы: если места мало, он
    # уходит на следующую вместе со своим текстом.
    return [CondPageBreak(30 * mm), Paragraph(text, S["h2"])]


def h3(text):
    return Paragraph(text, S["h3"])


def p(text):
    return Paragraph(text, S["p"])


def bullets(items):
    return ListFlowable(
        [ListItem(Paragraph(t, S["li"]), leftIndent=14, value="circle") for t in items],
        bulletType="bullet", start="circle", bulletColor=EMBER,
        bulletFontSize=5, leftIndent=14, spaceAfter=8,
    )


def steps(items):
    return ListFlowable(
        [ListItem(Paragraph(t, S["li"]), leftIndent=16) for t in items],
        bulletType="1", bulletFontName="Body-Bold", bulletColor=EMBER,
        bulletFontSize=9.5, leftIndent=16, spaceAfter=8,
    )


def callout(text, color=EMBER, bg=PANEL):
    t = Table([[Paragraph(text, S["quote"])]], colWidths=[CONTENT_W])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), bg),
        ("LINEBEFORE", (0, 0), (0, -1), 2.5, color),
        ("LEFTPADDING", (0, 0), (-1, -1), 11),
        ("RIGHTPADDING", (0, 0), (-1, -1), 11),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
    ]))
    return KeepTogether([t, Spacer(1, 10)])


def code(text):
    t = Table([[Preformatted(text.strip("\n"), S["code"])]], colWidths=[CONTENT_W])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), CODEBG),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
    ]))
    return KeepTogether([t, Spacer(1, 10)])


def table(header, rows, widths, first_bold=True):
    """Таблица с тёмной шапкой. `widths` — доли ширины страницы."""
    data = [[Paragraph(c, S["th"]) for c in header]]
    for r in rows:
        data.append([
            Paragraph(str(c), S["tdb"] if (i == 0 and first_bold) else S["td"])
            for i, c in enumerate(r)
        ])
    t = Table(data, colWidths=[w * CONTENT_W for w in widths], repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), INK),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, PANEL]),
        ("GRID", (0, 0), (-1, -1), 0.4, RULE),
        ("LINEBELOW", (0, 0), (-1, 0), 1.2, EMBER),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 4.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4.5),
    ]))
    return KeepTogether([t, Spacer(1, 10)]) if len(rows) < 14 else t


def screenshot(name, caption, width=CONTENT_W):
    path = SCREENS / f"{name}.png"
    if not path.exists():
        return Spacer(1, 1)
    from PIL import Image as PILImage
    w, h = PILImage.open(path).size
    img = Image(str(path), width=width, height=width * h / w)
    frame = Table([[img]], colWidths=[width])
    frame.setStyle(TableStyle([
        ("BOX", (0, 0), (-1, -1), 0.8, INK),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
    ]))
    return KeepTogether([frame, Paragraph(caption, S["cap"])])


# --- страница ----------------------------------------------------------------

def decorate(canvas, doc):
    canvas.saveState()
    canvas.setFont("Body", 8)
    canvas.setFillColor(ASH)
    canvas.drawString(MARGIN, 12 * mm, "SHADOWSTRIKE — руководство")
    canvas.drawRightString(PAGE_W - MARGIN, 12 * mm, str(doc.page))
    canvas.setStrokeColor(RULE)
    canvas.setLineWidth(0.4)
    canvas.line(MARGIN, 16 * mm, PAGE_W - MARGIN, 16 * mm)
    canvas.setFillColor(EMBER)
    canvas.rect(0, PAGE_H - 4 * mm, PAGE_W * 0.18, 4 * mm, stroke=0, fill=1)
    canvas.restoreState()


def cover_decorate(canvas, doc):
    canvas.saveState()
    canvas.setFillColor(INK)
    canvas.rect(0, PAGE_H - 12 * mm, PAGE_W, 12 * mm, stroke=0, fill=1)
    canvas.setFillColor(EMBER)
    canvas.rect(0, PAGE_H - 12 * mm, PAGE_W * 0.34, 12 * mm, stroke=0, fill=1)
    canvas.rect(MARGIN, 28 * mm, 46 * mm, 3.2 * mm, stroke=0, fill=1)
    canvas.restoreState()


class Doc(BaseDocTemplate):
    def afterFlowable(self, flowable):
        # Каждый заголовок раздела — строка оглавления и закладка в PDF.
        if isinstance(flowable, Heading):
            text = flowable.getPlainText()
            key = f"h{id(flowable)}"
            self.canv.bookmarkPage(key)
            self.canv.addOutlineEntry(text, key, level=0, closed=False)
            self.notify("TOCEntry", (0, text, self.page, key))


